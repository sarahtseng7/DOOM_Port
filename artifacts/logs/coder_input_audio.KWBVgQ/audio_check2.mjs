import { createRequire } from 'module';
const require = createRequire('/Users/sarahtseng/Projects/fellowship-loop-capstone/tests/');
const { chromium } = require('playwright');
import http from 'http'; import fs from 'fs'; import path from 'path';
const [dist, out] = process.argv.slice(2);
const mime = { '.html':'text/html', '.js':'text/javascript', '.wasm':'application/wasm' };
const srv = http.createServer((q, r) => { const f = path.join(dist, q.url === '/' ? 'index.html' : q.url.split('?')[0]);
  fs.readFile(f, (e, d) => { if (e) { r.writeHead(404); r.end(); } else { r.writeHead(200, {'content-type': mime[path.extname(f)]||'application/octet-stream'}); r.end(d);} }); });
await new Promise(r => srv.listen(0, '127.0.0.1', r));
const b = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] });
const pg = await b.newPage({ viewport: { width: 1280, height: 800 } });
const errs = []; pg.on('pageerror', e => errs.push(String(e)));
await pg.goto(`http://127.0.0.1:${srv.address().port}/`);
await pg.waitForFunction(() => window.Module && Module._cap_ready && Module._cap_ready() === 1, null, { timeout: 60000 });
const key = async (k, ms=120) => { await pg.keyboard.down(k); await pg.waitForTimeout(ms); await pg.keyboard.up(k); await pg.waitForTimeout(250); };
for (let i=0;i<4;i++) await key('Enter');
await pg.waitForTimeout(3000);
const peak = async (ms) => { await pg.evaluate(() => CapAudio.resetPeak()); await pg.waitForTimeout(ms); return pg.evaluate(() => CapAudio.stats().maxPeak); };
const res = { errs };
res.musicPeak = await peak(1500);
res.delivered0 = await pg.evaluate(() => Module._cap_input_delivered_count());
const t0 = await pg.evaluate(() => Module._cap_tic_count());
await key('ArrowUp', 800); await key('ArrowLeft', 200);
res.delivered1 = await pg.evaluate(() => Module._cap_input_delivered_count());
res.ticsAdvanced = (await pg.evaluate(() => Module._cap_tic_count())) - t0;
await key('Pause');   // engine pause -> S_PauseSound -> music pause
await pg.waitForTimeout(500);
res.paused = await pg.evaluate(() => CapAudio.stats());
res.pausedPeak = await peak(1200);
await key('Pause');
await pg.waitForTimeout(500);
res.resumedPeak = await peak(1500);
res.resumed = await pg.evaluate(() => CapAudio.stats());
fs.writeFileSync(out + '/audio_check2.json', JSON.stringify(res, null, 2));
console.log(JSON.stringify(res, null, 2));
await b.close(); srv.close();
