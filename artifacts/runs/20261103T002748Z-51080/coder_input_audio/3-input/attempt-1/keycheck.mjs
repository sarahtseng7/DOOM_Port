// Ad-hoc check of web/input_audio.js with a stubbed Module (not a protected acceptance test).
import { chromium } from '../../../../../../tests/node_modules/playwright/index.mjs';
import fs from 'fs';
const src = fs.readFileSync('web/input_audio.js','utf8');
const b = await chromium.launch(); const p = await b.newPage();
await p.setContent('<body></body>');
await p.evaluate(() => { window.log=[]; window.Module={calledRun:true,_cap_input_event:(d,k)=>log.push([d,k]),_cap_input_reset:()=>log.push(['reset'])}; });
await p.addScriptTag({content:src});
const res = [];
const fire = (type, init) => p.evaluate(([t,i]) => { const e=new KeyboardEvent(t,Object.assign({bubbles:true,cancelable:true},i)); window.dispatchEvent(e); return e.defaultPrevented; }, [type, init]);
const getlog = () => p.evaluate(() => JSON.stringify(log.splice(0)));
const chk = (n, ok, d) => { res.push({n, ok, d}); console.log(ok?'PASS':'FAIL', n, d); };
await fire('keydown',{code:'ArrowUp'}); await fire('keydown',{code:'ArrowUp',repeat:true});
chk('repeat dropped', await getlog()==='[[1,173]]', '');
await p.evaluate(()=>window.dispatchEvent(new Event('blur')));
chk('blur resets', await getlog()==='["reset"]'.replace('"reset"','["reset"]'), '');
await fire('keydown',{code:'ArrowUp',repeat:true});
chk('F2 repeat after blur re-presses', await getlog()==='[[1,173]]', '');
await fire('keyup',{code:'ArrowUp'}); await getlog();
chk('F5 not prevented', (await fire('keydown',{code:'F5'}))===false, '');
chk('Ctrl+R not prevented', (await fire('keydown',{code:'KeyR',ctrlKey:true}))===false, '');
chk('ArrowUp prevented', (await fire('keydown',{code:'ArrowDown'}))===true, '');
await fire('keyup',{code:'F5'}); await fire('keyup',{code:'KeyR'}); await fire('keyup',{code:'ArrowDown'}); await getlog();
await fire('keydown',{code:'ControlLeft'}); await fire('keydown',{code:'ControlRight'}); await fire('keyup',{code:'ControlLeft'});
let l1 = await getlog(); await fire('keyup',{code:'ControlRight'}); let l2 = await getlog();
chk('L+R ctrl release only at last', l1==='[[1,163]]' && l2==='[[0,163]]', l1+l2);
await fire('keydown',{code:'KeyW'}); await getlog();
await p.evaluate(()=>{Object.defineProperty(document,'hidden',{value:true,configurable:true});document.dispatchEvent(new Event('visibilitychange'));});
chk('hidden resets', await getlog()==='[["reset"]]', '');
await b.close();
fs.writeFileSync(process.argv[2], JSON.stringify(res,null,1));
process.exit(res.every(r=>r.ok)?0:1);
